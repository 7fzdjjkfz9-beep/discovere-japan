@app.post('/report/{post_id}')
async def report(post_id:int,request:Request,comment_id:int=Form(0)):
 owner,fresh=identity(request)
 with conn() as c:
  if comment_id:
   target = c.execute('SELECT id FROM comments WHERE id=%s AND post_id=%s AND hidden=0 FOR UPDATE',(comment_id,post_id)).fetchone()
  else:
   target = c.execute('SELECT id FROM posts WHERE id=%s AND hidden=0 FOR UPDATE',(post_id,)).fetchone()
  if not target: raise HTTPException(404)
  inserted = c.execute('INSERT INTO guest_reports(post_id,comment_id,owner) VALUES(%s,%s,%s) ON CONFLICT DO NOTHING RETURNING post_id',(post_id,comment_id,owner)).fetchone()
  if inserted:
   rate(c,owner,'report',10)
   if comment_id:
    c.execute('UPDATE comments SET reports=reports+1,hidden=CASE WHEN reports>=2 THEN 1 ELSE hidden END WHERE id=%s',(comment_id,))
   else:
    c.execute('UPDATE posts SET reports=reports+1,hidden=CASE WHEN reports>=2 THEN 1 ELSE hidden END WHERE id=%s',(post_id,))
 return response_cookie(RedirectResponse('/?tab=community',303),owner,fresh)

